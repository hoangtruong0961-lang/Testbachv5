/**
 * Fixes duration metadata in MP4 files (mvhd, tkhd, mdhd, mehd boxes)
 * generated by MediaRecorder or encoders that omit or zero duration metadata.
 */
export async function fixMp4Duration(blob: Blob, durationInSeconds: number): Promise<Blob> {
  if (!durationInSeconds || durationInSeconds <= 0) return blob;

  try {
    const arrayBuffer = await blob.arrayBuffer();
    const bytes = new Uint8Array(arrayBuffer);
    const view = new DataView(arrayBuffer);

    let movieTimescale = 1000;

    function scanBoxes(start: number, end: number) {
      let pos = start;
      while (pos + 8 <= end) {
        let boxSize = view.getUint32(pos);
        const boxType = String.fromCharCode(
          bytes[pos + 4],
          bytes[pos + 5],
          bytes[pos + 6],
          bytes[pos + 7]
        );

        let headerSize = 8;
        if (boxSize === 1) {
          if (pos + 16 > end) break;
          const high = view.getUint32(pos + 8);
          const low = view.getUint32(pos + 12);
          boxSize = high * 4294967296 + low;
          headerSize = 16;
        } else if (boxSize === 0) {
          boxSize = end - pos;
        }

        if (boxSize < headerSize || pos + boxSize > end) {
          break;
        }

        const payloadStart = pos + headerSize;
        const payloadEnd = pos + boxSize;

        if (
          boxType === 'moov' ||
          boxType === 'trak' ||
          boxType === 'mdia' ||
          boxType === 'minf' ||
          boxType === 'mvex'
        ) {
          scanBoxes(payloadStart, payloadEnd);
        } else if (boxType === 'mvhd') {
          const version = bytes[payloadStart];
          let timescaleOffset = payloadStart + 12;
          let durationOffset = payloadStart + 16;
          if (version === 1) {
            timescaleOffset = payloadStart + 20;
            durationOffset = payloadStart + 24;
          }
          if (timescaleOffset + 4 <= payloadEnd) {
            movieTimescale = view.getUint32(timescaleOffset) || 1000;
          }
          const targetDurationUnits = Math.round(durationInSeconds * movieTimescale);

          if (version === 0 && durationOffset + 4 <= payloadEnd) {
            view.setUint32(durationOffset, targetDurationUnits);
          } else if (version === 1 && durationOffset + 8 <= payloadEnd) {
            const high = Math.floor(targetDurationUnits / 4294967296);
            const low = targetDurationUnits % 4294967296;
            view.setUint32(durationOffset, high);
            view.setUint32(durationOffset + 4, low);
          }
        } else if (boxType === 'tkhd') {
          const version = bytes[payloadStart];
          let durationOffset = payloadStart + 20;
          if (version === 1) {
            durationOffset = payloadStart + 28;
          }
          const targetDurationUnits = Math.round(durationInSeconds * movieTimescale);

          if (version === 0 && durationOffset + 4 <= payloadEnd) {
            view.setUint32(durationOffset, targetDurationUnits);
          } else if (version === 1 && durationOffset + 8 <= payloadEnd) {
            const high = Math.floor(targetDurationUnits / 4294967296);
            const low = targetDurationUnits % 4294967296;
            view.setUint32(durationOffset, high);
            view.setUint32(durationOffset + 4, low);
          }
        } else if (boxType === 'mdhd') {
          const version = bytes[payloadStart];
          let timescaleOffset = payloadStart + 12;
          let durationOffset = payloadStart + 16;
          if (version === 1) {
            timescaleOffset = payloadStart + 20;
            durationOffset = payloadStart + 24;
          }
          let mediaTimescale = movieTimescale;
          if (timescaleOffset + 4 <= payloadEnd) {
            mediaTimescale = view.getUint32(timescaleOffset) || movieTimescale;
          }
          const targetDurationUnits = Math.round(durationInSeconds * mediaTimescale);

          if (version === 0 && durationOffset + 4 <= payloadEnd) {
            view.setUint32(durationOffset, targetDurationUnits);
          } else if (version === 1 && durationOffset + 8 <= payloadEnd) {
            const high = Math.floor(targetDurationUnits / 4294967296);
            const low = targetDurationUnits % 4294967296;
            view.setUint32(durationOffset, high);
            view.setUint32(durationOffset + 4, low);
          }
        } else if (boxType === 'mehd') {
          const version = bytes[payloadStart];
          const durationOffset = payloadStart + 4;
          const targetDurationUnits = Math.round(durationInSeconds * movieTimescale);

          if (version === 0 && durationOffset + 4 <= payloadEnd) {
            view.setUint32(durationOffset, targetDurationUnits);
          } else if (version === 1 && durationOffset + 8 <= payloadEnd) {
            const high = Math.floor(targetDurationUnits / 4294967296);
            const low = targetDurationUnits % 4294967296;
            view.setUint32(durationOffset, high);
            view.setUint32(durationOffset + 4, low);
          }
        }

        pos += boxSize;
      }
    }

    scanBoxes(0, bytes.length);
    return new Blob([bytes.buffer], { type: blob.type || 'video/mp4' });
  } catch (err) {
    console.warn('[fixMp4Duration] Failed to patch MP4 duration:', err);
    return blob;
  }
}

/**
 * Adjusts volume of an AudioBuffer using OfflineAudioContext.
 */
async function adjustAudioBufferVolume(
  original: AudioBuffer | null,
  volume: number = 1.0,
  targetDuration: number
): Promise<AudioBuffer | null> {
  if (!original) return null;
  if (volume === 0) return null; // Muted
  if (volume === 1.0) return original; // No change needed

  const sampleRate = original.sampleRate;
  const numChannels = original.numberOfChannels;
  const duration = Math.max(original.duration, targetDuration);

  const offlineCtx = new OfflineAudioContext(
    numChannels,
    Math.ceil(sampleRate * duration),
    sampleRate
  );

  const originalSource = offlineCtx.createBufferSource();
  originalSource.buffer = original;

  const gainNode = offlineCtx.createGain();
  gainNode.gain.value = volume;

  originalSource.connect(gainNode);
  gainNode.connect(offlineCtx.destination);
  originalSource.start(0);

  return await offlineCtx.startRendering();
}

/**
 * Mixes original video audio and TTS voiceover audio together.
 */
async function mixAudioBuffers(
  original: AudioBuffer | null,
  tts: AudioBuffer | null,
  targetDuration: number,
  videoVolume: number = 1.0
): Promise<AudioBuffer | null> {
  if (!original && !tts) return null;
  if (original && !tts) {
    return await adjustAudioBufferVolume(original, videoVolume, targetDuration);
  }
  if (!original && tts) return tts;

  // Both original and TTS exist
  if (videoVolume === 0) {
    return tts;
  }

  const sampleRate = original!.sampleRate;
  const numChannels = Math.max(original!.numberOfChannels, tts!.numberOfChannels);
  const duration = Math.max(original!.duration, tts!.duration, targetDuration);

  const offlineCtx = new OfflineAudioContext(
    numChannels,
    Math.ceil(sampleRate * duration),
    sampleRate
  );

  // 1. Play original audio with videoVolume applied
  const originalSource = offlineCtx.createBufferSource();
  originalSource.buffer = original!;

  if (videoVolume !== 1.0) {
    const gainNode = offlineCtx.createGain();
    gainNode.gain.value = videoVolume;
    originalSource.connect(gainNode);
    gainNode.connect(offlineCtx.destination);
  } else {
    originalSource.connect(offlineCtx.destination);
  }
  originalSource.start(0);

  // 2. Play TTS audio (mono will be automatically upmixed to stereo/numChannels)
  const ttsSource = offlineCtx.createBufferSource();
  ttsSource.buffer = tts!;
  ttsSource.connect(offlineCtx.destination);
  ttsSource.start(0);

  return await offlineCtx.startRendering();
}

